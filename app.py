def _png_buf(img: Image.Image, size=(420, 420)):
    buf = io.BytesIO()
    img.convert("RGB").resize(size).save(buf, format="PNG")
    buf.seek(0)
    return buf


def build_pdf(patient, img, probs, top_idx, model_name) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
                            topMargin=1.8 * cm, bottomMargin=1.8 * cm)
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], textColor=colors.HexColor("#4338ca"), fontSize=22)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=colors.HexColor("#1e293b"), spaceBefore=10)
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=10, leading=14)
    small = ParagraphStyle("s", parent=body, fontSize=8.5, textColor=colors.HexColor("#92400e"))

    top = CLASSES[top_idx]
    els = [Paragraph("NeuroVision AI - Brain MRI Diagnostic Report", h1),
           Paragraph(datetime.datetime.now().strftime("Generated on %d %B %Y, %H:%M"), body),
           Spacer(1, 10)]

    info = [["Patient name", patient["name"] or "-"], ["Patient ID", patient["pid"] or "-"],
            ["Age / Sex", f"{patient['age']} / {patient['sex']}"], ["Scan file", patient["file"]]]
           
    t = Table(info, colWidths=[4 * cm, 12 * cm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eef2ff")),
        ("GRID", (0, 0), (-1, -1), .5, colors.HexColor("#c7d2fe")),
        ("FONTSIZE", (0, 0), (-1, -1), 10), ("PADDING", (0, 0), (-1, -1), 6)]))
    els += [t, Spacer(1, 12), Paragraph("AI Finding", h2),
            Paragraph(f"<b>Predicted class:</b> {LABELS[top]} &nbsp;&nbsp; "
                      f"<b>Confidence:</b> {probs[top_idx] * 100:.1f}%", body),
            Spacer(1, 4), Paragraph(INFO[top], body), Spacer(1, 10),
            Paragraph("MRI scan", h2),
            RLImage(_png_buf(img), 8 * cm, 8 * cm, hAlign="LEFT"),
            Spacer(1, 10), Paragraph("Class probabilities", h2)]

    rows = [["Class", "Probability"]] + [[LABELS[c], f"{p * 100:.2f}%"]
                                          for c, p in sorted(zip(CLASSES, probs), key=lambda z: -z[1])]
    pt = Table(rows, colWidths=[8 * cm, 4 * cm])
    pt.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#4338ca")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), .5, colors.HexColor("#c7d2fe")), ("PADDING", (0, 0), (-1, -1), 6)]))
    els += [pt, Spacer(1, 16), Paragraph(f"<b>Disclaimer:</b> {DISCLAIMER}", small)]
    doc.build(els)
    return buf.getvalue()


