# Model (downloaded automatically from Hugging Face Hub, cached after first run)
# ----------------------------------------------------------------------------
@st.cache_resource(show_spinner="Downloading / loading pretrained model...")
def load_model(repo_id: str, token: str):
    import tensorflow as tf
    import keras
    from huggingface_hub import hf_hub_download

    model_path = hf_hub_download(
        repo_id=repo_id,
        filename="best_model.keras",
        token=token or None,
    )

    return keras.models.load_model(
        model_path,
        compile=False,
    )

def input_size(model):
    try:
        h, w = model.input_shape[1:3]
        return int(w), int(h)
    except Exception:
        return 299, 299  # Xception default


def predict(model, img: Image.Image):
    w, h = input_size(model)
    x = np.asarray(img.convert("RGB").resize((w, h)), dtype="float32") / 255.0
    probs = np.asarray(model.predict(x[None, ...], verbose=0)[0], dtype="float64")
    if not np.isclose(probs.sum(), 1.0, atol=1e-3):  # model returned logits
        e = np.exp(probs - probs.max())
        probs = e / e.sum()
    return probs


